# ========================================
# 改善版 generate_copy 関数のプロンプト
# ========================================

def get_improved_system_prompt():
    """改善版システムプロンプトを返す"""
    return SYSTEM_PROMPT_APPAREL_EXPERT


def get_improved_user_prompt(visible_facts: str, known_facts: str = ""):
    """改善版ユーザープロンプトを返す（Chain-of-Thought + Few-shot）"""
    
    user_prompt = f"""
【画像から読み取った情報】
{visible_facts}

【補足情報】
{known_facts if known_facts else "（補足情報なし）"}

{TASK_APPAREL_DESCRIPTION_COT}

{FEW_SHOT_EXAMPLES}

【実行】
上記の段階的プロセスに従って、商品説明文を生成し、JSON 形式で出力してください。
"""
    
    return user_prompt


